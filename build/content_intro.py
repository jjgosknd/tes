def toc():
    """Содержание. Делаем как обычные параграфы с выровненной справа нумерацией страниц
    через TAB w:leader=dot. Поскольку нумерация автоматическая в Word делается через поле TOC,
    а пользователь может всегда обновить F9, мы сделаем простую таблицу содержания."""

    items = [
        ("ВВЕДЕНИЕ", "3", 0),
        ("ГЛАВА 1. АНАЛИЗ ПРЕДМЕТНОЙ ОБЛАСТИ И СУЩЕСТВУЮЩИХ РЕШЕНИЙ", "6", 0),
        ("1.1 Характеристика предметной области и постановка задачи", "6", 1),
        ("1.2 Анализ существующих программных решений (аналогов)", "9", 1),
        ("1.3 Обоснование необходимости разработки собственной системы", "13", 1),
        ("Выводы по главе 1", "15", 1),
        ("ГЛАВА 2. ПРОЕКТИРОВАНИЕ МОБИЛЬНОГО ПРИЛОЖЕНИЯ", "16", 0),
        ("2.1 Формирование требований к системе", "16", 1),
        ("2.2 Обоснование выбора архитектуры и технологического стека", "19", 1),
        ("2.3 Проектирование структуры программной системы", "22", 1),
        ("Выводы по главе 2", "30", 1),
        ("ГЛАВА 3. РЕАЛИЗАЦИЯ И ТЕСТИРОВАНИЕ ПРОГРАММНОЙ СИСТЕМЫ", "31", 0),
        ("3.1 Описание структуры проекта", "31", 1),
        ("3.2 Реализация ключевых модулей приложения", "34", 1),
        ("3.3 Пользовательский интерфейс мобильного приложения", "39", 1),
        ("3.4 Тест-план и результаты тестирования", "43", 1),
        ("Выводы по главе 3", "47", 1),
        ("ГЛАВА 4. ЭКОНОМИЧЕСКОЕ ОБОСНОВАНИЕ РАЗРАБОТКИ", "48", 0),
        ("4.1 Календарный план разработки программной системы", "48", 1),
        ("4.2 Расчёт затрат на разработку программной системы", "50", 1),
        ("4.3 Оценка эффективности разработки программного продукта", "52", 1),
        ("Выводы по главе 4", "53", 1),
        ("ЗАКЛЮЧЕНИЕ", "54", 0),
        ("СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ", "56", 0),
        ("ПРИЛОЖЕНИЕ А. ЛИСТИНГИ КЛЮЧЕВЫХ ПРОГРАММНЫХ МОДУЛЕЙ", "60", 0),
        ("ПРИЛОЖЕНИЕ Б. ЭКРАННЫЕ ФОРМЫ И РУКОВОДСТВО ПОЛЬЗОВАТЕЛЯ", "65", 0),
    ]
    out = [p("СОДЕРЖАНИЕ", align="center", first_line=False, size=28, bold=True, before=0, after=240)]
    for text, page, lvl in items:
        # Для уровня 1 — отступ 240. Используем кастомный TAB с лидером.
        ind_left = 480 if lvl == 1 else 0
        bold = (lvl == 0 and ("ГЛАВА" in text or text in ("ВВЕДЕНИЕ", "ЗАКЛЮЧЕНИЕ")
                              or text.startswith("СПИСОК") or text.startswith("ПРИЛОЖЕНИЕ")))
        # параграф с tab-стопом справа
        ppr = (
            '<w:pPr>'
            '<w:tabs><w:tab w:val="right" w:leader="dot" w:pos="9628"/></w:tabs>'
            '<w:spacing w:line="360" w:lineRule="auto" w:after="0" w:before="0"/>'
            f'<w:ind w:left="{ind_left}" w:firstLine="0"/>'
            '<w:jc w:val="left"/>'
            '<w:rPr><w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman"/>'
            f'{"<w:b/>" if bold else ""}<w:sz w:val="28"/></w:rPr>'
            '</w:pPr>'
        )
        rpr_b = '<w:rPr><w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman"/>' + ('<w:b/>' if bold else '') + '<w:sz w:val="28"/></w:rPr>'
        para = (
            f'<w:p>{ppr}'
            f'<w:r>{rpr_b}<w:t xml:space="preserve">{text}</w:t></w:r>'
            f'<w:r>{rpr_b}<w:tab/></w:r>'
            f'<w:r>{rpr_b}<w:t>{page}</w:t></w:r>'
            f'</w:p>'
        )
        out.append(para)
    # Не добавляем page_break — переключение на следующую страницу будет
    # обеспечено разделом (sectPr) и pageBreakBefore у заголовка ВВЕДЕНИЕ.
    return ''.join(out)


